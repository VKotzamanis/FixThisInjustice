// scripts/limelight-side-by-side.mjs
//
// Prints docs/design/2026-09-02-limelight-side-by-side.md on stdout: one table per screen, the
// clinical default beside the limelight string and the board string, with an empty column for the
// user to mark up. P9 Task 13.
//
// Regenerate after any edit to the three tables:
//
//   node scripts/limelight-side-by-side.mjs > docs/design/2026-09-02-limelight-side-by-side.md
//
// The output is a function of the tables alone, so two runs on one tree agree byte for byte. No
// string is retyped here: every cell is read from src/content/copy.ts through the same module the
// app imports.
//
// Vite's Node API loads that module because it imports './copy.board' with no extension, which
// Node's own resolver rejects. This is the reason scripts/copy-wordcount.mjs gives, and the two
// scripts load the table the same way.
import { execFileSync } from 'node:child_process';
import { createServer } from 'vite';

/**
 * The screens, in the order the page prints them, each with the paths that render its strings.
 *
 * A key lands under the FIRST screen whose paths mention it, so every row appears once. The order
 * is the tab order, then the popups, then what is left. `git grep` is the lookup, so a key a
 * component builds by concatenation is not seen; no call site in this tree does that.
 */
const SCREENS = [
  ['Today', ['src/ui/views/TodayView.tsx']],
  ['Train', ['src/ui/views/TrainView.tsx', 'src/ui/views/train']],
  ['Plan', ['src/ui/views/PlanView.tsx']],
  ['Targets', ['src/ui/views/TargetsView.tsx']],
  ['Log', ['src/ui/views/LogView.tsx', 'src/ui/views/ExportView.tsx']],
  ['Atlas', ['src/ui/views/AtlasView.tsx']],
  [
    'Settings',
    [
      'src/ui/views/SettingsView.tsx',
      'src/ui/settings',
      'src/ui/components/ReminderSettingsPanel.tsx',
      'src/ui/components/InstallGuide.tsx',
    ],
  ],
  [
    'Popups, toasts and the boot screen',
    ['src/ui/components', 'src/ui/motivation', 'src/ui/migration', 'src/app'],
  ],
  ['Everywhere else', ['src']],
];

/**
 * The keys one path set mentions, as a set.
 *
 * BOTH QUOTE STYLES. A view that calls the hook writes `c('button.skipToday')` and a view that
 * hands the key to a component writes `copyKey="button.skipToday"`, so a single-quote grep files
 * half of Today's controls under the fallback screen. `execFileSync` passes the pattern as one
 * argument, which keeps the two quote characters out of a shell.
 */
function keysIn(paths) {
  let out;
  try {
    out = execFileSync(
      'git',
      ['grep', '-ohE', `['"][a-z][a-zA-Z0-9_.]*\\.[a-zA-Z0-9_.]*['"]`, '--', ...paths],
      { encoding: 'utf8' },
    );
  } catch {
    // git grep exits 1 when a path set mentions no key at all. That is an empty set, not an error.
    out = '';
  }
  return new Set(out.split('\n').map((line) => line.replace(/['"]/g, '').trim()).filter(Boolean));
}

/** A markdown cell. The pipe is the only character that would split a row. */
function cell(value) {
  return value.replace(/\|/g, '\\|');
}

const server = await createServer({
  configFile: false,
  server: { middlewareMode: true },
  appType: 'custom',
  logLevel: 'error',
});
const copy = await server.ssrLoadModule('/src/content/copy.ts');
await server.close();

const { BOARD_COPY, DEFAULT_COPY, LIMELIGHT_COPY } = copy;
const rows = [...new Set([...Object.keys(LIMELIGHT_COPY), ...Object.keys(BOARD_COPY)])].sort();

const placed = new Map();
for (const [screen, paths] of SCREENS) {
  const used = keysIn(paths);
  for (const key of rows) {
    if (!placed.has(key) && used.has(key)) placed.set(key, screen);
  }
}
for (const key of rows) {
  if (!placed.has(key)) placed.set(key, 'No call site found');
}

