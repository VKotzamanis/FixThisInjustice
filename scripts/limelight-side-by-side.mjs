lines.push('');
lines.push(
  'One table per screen, in tab order, then the popups. A key appears once, under the first screen',
);
lines.push(
  'that renders it, so a control shared by two screens is listed with the earlier one. `same` in',
);
lines.push(
  'the board column means the departures board has no row and the clinical string stands there.',
);
lines.push('');

let printed = 0;
for (const [screen] of [...SCREENS, ['No call site found']]) {
  const keys = rows.filter((key) => placed.get(key) === screen);
  if (keys.length === 0) continue;
  lines.push(`## ${screen} (${keys.length})`);
  lines.push('');
  lines.push('| Key | Default (clinical) | Limelight | Board | Your mark |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const key of keys) {
    const limelight = LIMELIGHT_COPY[key] ?? 'same';
    const board = BOARD_COPY[key] ?? 'same';
    lines.push(
      `| \`${key}\` | ${cell(DEFAULT_COPY[key])} | ${cell(limelight)} | ${cell(board)} |  |`,
    );
    printed += 1;
  }
  lines.push('');
}

lines.push('## Counts');
lines.push('');
lines.push(`- Rows on this page: ${printed}.`);
lines.push(`- Keys in the limelight table: ${Object.keys(LIMELIGHT_COPY).length}.`);
lines.push(`- Keys in the board table: ${Object.keys(BOARD_COPY).length}.`);
lines.push(`- Keys in the clinical default table: ${Object.keys(DEFAULT_COPY).length}.`);
lines.push('');

process.stdout.write(lines.join('\n'));
