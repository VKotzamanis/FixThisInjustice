lines.push('taste.');
lines.push('');
lines.push(
  'A skin changes words, never facts. Every `{slot}` is a number the app computed, so it survives',
);
lines.push(
  'every rewrite, and so do the units and the defined quantity names: `60 kg`, `8 reps` and',
);
lines.push('`beverage intake` read the same on every skin.');
lines.push('');
